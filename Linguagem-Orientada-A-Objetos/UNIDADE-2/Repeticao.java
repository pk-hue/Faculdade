public class Repeticao {
    public static void main(String[] args) {
        int i  = 1;

        while(i <= 10){
            System.out.println("Repetição: " + i);
            i++;
        }

        System.out.println("Fim do programa!");

        //Do While
        int j = 1;

        do{
            System.out.println("Repetição Do While: " + j);
            j++;
        }while(j <= 10);
    }

}